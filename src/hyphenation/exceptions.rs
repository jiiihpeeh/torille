//! Explicit break exceptions.
//!
//! Patterns are a baseline, not a verdict. A loanword can contain a
//! vowel sequence that Finnish line typography normally avoids, and a
//! proper name can have a break that no general rule predicts. The table
//! here is deliberately small: a missing *compound* boundary belongs in
//! the morphology layer, not in a growing suffix list.
//!
//! Built-in rows live in `data/hyphenation/exceptions.csv`. `build.rs`
//! compiles them into a sorted static table (below), which is searched by
//! binary search; callers can still build an [`Exceptions`] value with their
//! own allow/deny entries.

use std::collections::HashMap;
use std::sync::OnceLock;

/// One built-in rule, generated from `data/hyphenation/exceptions.csv`.
pub(crate) struct Builtin {
    pub(crate) word: &'static str,
    pub(crate) allow: &'static [usize],
    pub(crate) deny: &'static [usize],
}

// `EXCEPTIONS`, generated by `build/hyphenation.rs`; sorted by `word`.
include!(concat!(env!("OUT_DIR"), "/hyphenation_exceptions.rs"));

fn builtin(word: &str) -> Option<&'static Builtin> {
    EXCEPTIONS
        .binary_search_by(|rule| rule.word.cmp(word))
        .ok()
        .map(|at| &EXCEPTIONS[at])
}

/// Allow and deny offsets for one spelling.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
struct Rule {
    allow: Vec<usize>,
    deny: Vec<usize>,
}

/// Explicit break overrides, keyed by lower-cased spelling.
///
/// Offsets are character counts from the start of the word: an allow
/// offset of `4` means "a break is permitted after the fourth
/// character", matching [`super::HyphenationPoint::char_offset`].
///
/// The built-in table is static; `rules` holds only the caller's additions.
#[derive(Clone, Debug, Default)]
pub struct Exceptions {
    rules: HashMap<String, Rule>,
}

static EMPTY: OnceLock<Exceptions> = OnceLock::new();

impl Exceptions {
    /// No exceptions at all.
    pub fn empty() -> Self {
        Self::default()
    }

    /// The built-in table from `data/hyphenation/exceptions.csv`.
    ///
    /// The returned value owns no rules: the built-in rows are the generated
    /// static table, consulted by the lookup methods below.
    pub fn finnish() -> &'static Self {
        EMPTY.get_or_init(Self::empty)
    }

    /// Permit a break after `char_offset` in `word`.
    pub fn allow(&mut self, word: &str, char_offset: usize) {
        let rule = self.rules.entry(word.to_lowercase()).or_default();
        if !rule.allow.contains(&char_offset) {
            rule.allow.push(char_offset);
        }
    }

    /// Forbid a break after `char_offset` in `word`, even when a pattern
    /// or the compound layer offers one.
    pub fn deny(&mut self, word: &str, char_offset: usize) {
        let rule = self.rules.entry(word.to_lowercase()).or_default();
        if !rule.deny.contains(&char_offset) {
            rule.deny.push(char_offset);
        }
    }

    /// Whether `word` has an explicit allow at `char_offset`.
    ///
    /// `word` must already be lowercase; the hyphenation pipeline lowercases
    /// once per word and reuses that key for every probe.
    pub(crate) fn allows(&self, word: &str, char_offset: usize) -> bool {
        self.rules
            .get(word)
            .is_some_and(|rule| rule.allow.contains(&char_offset))
            || builtin(word).is_some_and(|rule| rule.allow.contains(&char_offset))
    }

    /// Whether `word` has an explicit deny at `char_offset`.
    ///
    /// `word` must already be lowercase.
    pub(crate) fn denies(&self, word: &str, char_offset: usize) -> bool {
        self.rules
            .get(word)
            .is_some_and(|rule| rule.deny.contains(&char_offset))
            || builtin(word).is_some_and(|rule| rule.deny.contains(&char_offset))
    }

    /// Character offsets explicitly allowed for `word`.
    ///
    /// `word` must already be lowercase.
    pub(crate) fn allow_offsets(&self, word: &str) -> Vec<usize> {
        let mut out = self
            .rules
            .get(word)
            .map(|rule| rule.allow.clone())
            .unwrap_or_default();
        if let Some(rule) = builtin(word) {
            for &offset in rule.allow {
                if !out.contains(&offset) {
                    out.push(offset);
                }
            }
        }
        out
    }

    /// Character offsets explicitly denied for `word`.
    ///
    /// `word` must already be lowercase.
    pub(crate) fn deny_offsets(&self, word: &str) -> Vec<usize> {
        let mut out = self
            .rules
            .get(word)
            .map(|rule| rule.deny.clone())
            .unwrap_or_default();
        if let Some(rule) = builtin(word) {
            for &offset in rule.deny {
                if !out.contains(&offset) {
                    out.push(offset);
                }
            }
        }
        out
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_generated_table_has_the_loanword_exception() {
        let builtins = Exceptions::finnish();
        assert!(builtins.allows("kofeiini", 4));
        assert!(!builtins.denies("kofeiini", 4));
        assert!(EXCEPTIONS.windows(2).all(|w| w[0].word < w[1].word));
    }

    #[test]
    fn callers_can_allow_and_deny() {
        let mut exceptions = Exceptions::empty();
        exceptions.allow("Nimeni", 3);
        assert!(exceptions.allows("nimeni", 3));
        exceptions.deny("nimeni", 2);
        assert!(exceptions.denies("nimeni", 2));
    }
}
