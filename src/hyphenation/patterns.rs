//! Knuth–Liang pattern matching for Finnish.
//!
//! The vendored pattern file is the MIT-licensed school set from
//! `hyph-utf8` (`data/hyphenation/hyph-fi-x-school.tex`). `build.rs` parses it
//! at build time into the static `NODES` trie including in this module, so the
//! shipped binary has no pattern parser and no first-use initialisation.
//!
//! Pattern output is only the *ordinary* candidate set. Compound
//! boundaries come from [`super::compounds`], and the Finnish policy in
//! [`super::finnish`] decides what is typographically permitted.

use std::cell::RefCell;

/// Reusable buffers for one thread's pattern match.
///
/// Hyphenation is called on demand for many words; allocating the lowercased
/// character list, the padded copy and the score vector per call dwarfed the
/// trie walk. The buffers grow to the longest word seen and are reused.
#[derive(Default)]
struct Scratch {
    chars: Vec<char>,
    padded: Vec<char>,
    scores: Vec<u8>,
}

thread_local! {
    static SCRATCH: RefCell<Scratch> = RefCell::new(Scratch::default());
}

/// One trie node. A node that ends a pattern carries the pattern's score
/// values for the gaps before, between and after its letters.
pub(crate) struct Node {
    pub(crate) children: &'static [(char, u16)],
    pub(crate) values: &'static [u8],
}

// `LONGEST` and `NODES`, generated by `build/hyphenation.rs`.
include!(concat!(env!("OUT_DIR"), "/hyphenation_patterns.rs"));

/// The embedded Finnish pattern set.
pub(crate) struct PatternSet;

static FINNISH: PatternSet = PatternSet;

impl PatternSet {
    /// The break positions of `word`, as character counts from the start
    /// (always between 1 and `word.chars().count() - 1`).
    ///
    /// This is the raw pattern result. Minimum fragments, vowel rules and
    /// compound boundaries are applied by the caller.
    pub(crate) fn break_chars(&self, word: &str) -> Vec<usize> {
        SCRATCH.with_borrow_mut(|scratch| {
            scratch.chars.clear();
            scratch.chars.extend(
                word.chars()
                    .map(|c| c.to_lowercase().next().unwrap_or(c)),
            );
            let n = scratch.chars.len();
            if n < 2 {
                return Vec::new();
            }

            // A dot on either side lets patterns anchor at the word edge.
            scratch.padded.clear();
            scratch.padded.push('.');
            scratch.padded.extend_from_slice(&scratch.chars);
            scratch.padded.push('.');

            scratch.scores.clear();
            scratch.scores.resize(scratch.padded.len() + 1, 0);
            for start in 0..scratch.padded.len() {
                let mut node = 0usize;
                let last = (start + LONGEST).min(scratch.padded.len());
                for &c in &scratch.padded[start..last] {
                    let Some(next) = child(node, c) else {
                        break;
                    };
                    node = next;
                    let values = NODES[node].values;
                    if values.is_empty() {
                        continue;
                    }
                    for (offset, &value) in values.iter().enumerate() {
                        let at = start + offset;
                        if at < scratch.scores.len() {
                            scratch.scores[at] = scratch.scores[at].max(value);
                        }
                    }
                }
            }

        // `padded` is '.' + word + '.'. A break after original character
        // `c` sits at padded gap `c + 2`; `c` runs from 0 to n - 2.
            (0..n.saturating_sub(1))
                .filter(|&c| scratch.scores[c + 2] % 2 == 1)
                .map(|c| c + 1)
                .collect()
        })
    }
}

fn child(node: usize, c: char) -> Option<usize> {
    NODES[node]
        .children
        .binary_search_by_key(&c, |(letter, _)| *letter)
        .ok()
        .map(|at| usize::from(NODES[node].children[at].1))
}

/// The embedded Finnish pattern set.
pub(crate) fn finnish() -> &'static PatternSet {
    &FINNISH
}

#[cfg(test)]
mod tests {
    use super::*;

    fn chars(word: &str) -> Vec<usize> {
        finnish().break_chars(word)
    }

    #[test]
    #[allow(clippy::assertions_on_constants)]
    fn the_generated_table_is_present() {
        assert!(NODES.len() > 300, "generated trie is suspiciously small");
        assert!(LONGEST >= 4, "longest pattern is suspiciously short");
    }

    #[test]
    fn simple_words_follow_the_school_patterns() {
        assert_eq!(chars("matka"), vec![3]);
        assert_eq!(chars("kissa"), vec![3]);
        assert_eq!(chars("talo"), vec![2]);
        // The raw school set also gives `ra-di-o`; the policy removes
        // the final one-character fragment later.
        assert_eq!(chars("radio"), vec![2, 4]);
        assert_eq!(chars("paprika"), vec![3, 5]);
    }

    #[test]
    fn vowel_sequences_are_left_to_the_policy() {
        // The school set deliberately offers more than line typography
        // should use; `asia` has no two-character first fragment.
        assert_eq!(chars("asia"), vec![1, 3]);
    }

    #[test]
    fn a_pattern_match_is_not_confused_by_case() {
        assert_eq!(chars("Äänekoski"), chars("äänekoski"));
    }
}
