//! Derivative chains from flags on the word-list CSV.
//!
//! The base lexicon is `data/nykysuomensanalista.csv`, a word list whose first
//! four columns are the Kotus lemma, homonym, POS and class. The fifth column,
//! `Johdokset`, holds zero or more derivation chains on the **base** row:
//!
//! ```text
//! nostaa     verbi  53    FREQ:67
//! jouduttaa  verbi  53*C  REFL:52
//! sämpylä    substantiivi 12  VERB_OI:62>REFL_OI:52>ACTION_MINEN:38
//! ```
//!
//! A chain is `TYPE:CLASS` steps separated by `>`. Each step names a
//! productive rule, the class of its output, and the next step applies to that
//! output. The rule table supplies the suffix and its harmony twin plus the
//! stem operation. The derived lemmas are not Kotus rows; their forms are
//! generated by the normal class engines and cached once.
//!
//! This is what lets a creative but well-formed chain such as
//! `sämpylä -> sämpylöidä -> sämpylöityä -> sämpylöityminen` be recognised
//! without adding any of those words to the dictionary. The chain is data, not
//! a hard-coded suffix hack.
//!
//! The same table also carries the one-step noun/adjective rules
//! (`VERB_OI`, `ADJ_LLINEN`, `ADJ_INEN`, `ABSTRACT_UUS`, `VERB_ISTAA`,
//! `PRIV_TON`, `POSS_KAS`, `ADV_STI_*`, `ACTION_US_TA`,
//! `FREQ_ELLA`, `FREQ_SKELLA`, `MOM_AHTAA`, `CAUS_TTAA`, `ACTION_MA`,
//! `ACTION_IN`, `ACTION_E_*`, `ACTION_IN_*`, `AGENT_JA*`, `FREQ_ILLA`,
//! `ACTION_ILU`, `PLACE_MO`, `ADJ_MAINEN`, `ADJ_LLINEN_I`, `FEM_TAR`,
//! `NOUN_KKO`, `NOUN_STO`, `NOUN_KUNTA`, `DIM_NEN`); the bulk
//! generator applies them only to rows that
//! carry a Kotus class and only when the derived lemma is not already a
//! dictionary base.

