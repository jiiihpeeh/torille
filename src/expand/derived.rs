#[derive(Clone, Copy)]
enum StemRule {
    /// Drop the base's final vowel: `nostaa` -> `nosta`.
    DropVowel,
    /// Drop one of these endings: `sämpylöidä` -> `sämpylöi`.
    DropSuffix(&'static [&'static str]),
    /// Replace one of these endings: `onni` -> `onne` before `-llinen`.
    Replace(&'static [(&'static str, &'static str)]),
    /// Use the lemma stem unchanged: `raha` -> `rahaton`.
    Direct,
    /// Use the base's weak grade: `puku` -> `puvu` before `-ton`.
    Weak,
    /// Drop one of these endings and then take the strong grade:
    /// `hörpätä` -> `hörppä` before `-illä`.
    DropSuffixStrong(&'static [&'static str]),
    /// Replace one of these endings and then take the strong grade:
    /// `rynnätä` -> `ryntää` before `-jä`.
    ReplaceStrong(&'static [(&'static str, &'static str)]),
    /// Take the weak grade and then replace one of these endings:
    /// `lehti` -> `lehde` before `-tön`.
    ReplaceWeak(&'static [(&'static str, &'static str)]),
}

struct Rule {
    code: &'static str,
    input: PartOfSpeech,
    output: PartOfSpeech,
    suffix_back: &'static str,
    suffix_front: &'static str,
    class: u16,
    gradation: Option<Gradation>,
    /// Base Kotus classes this rule is restricted to. Empty means any.
    input_classes: &'static [u16],
    /// Keep the base word's gradation code (`jakaa 56*D` -> `jae 48*D`).
    inherit_gradation: bool,
    stem: StemRule,
}

