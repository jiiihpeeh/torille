//! Candidate generation must not move.
//!
//! The details of *scoring* a candidate list must not change what the
//! engine *produces*. That distinction is easy to lose quietly: a
//! pruning threshold or a distance limit touched "just to make the
//! benchmark cleaner" changes which candidates exist, which changes the
//! measured accuracy, and a test that only inspects scores would not
//! notice because it scores whatever list it is handed.
//!
//! So the engine's output is pinned here for a handful of inputs that
//! cover the shapes the dev split is made of: a transposition typo,
//! a doubled letter, an exact match, a shared-prefix neighbour, and a
//! long stem with suffix edits.
//!
//! If one of these assertions fires, decide deliberately whether the
//! candidate list *should* have changed. If it should, regenerate this
//! golden list; the accuracy numbers are then no longer comparable to
//! anything measured before.

use torille::suggest::{suggest, suggest_detailed};

/// `(query, expected candidates in deterministic order)`.
///
/// Generated by `suggest_correct --max 5 --distance 2 ...` on the
/// pre-refactor engine and copied verbatim.
const GOLDEN: &[(&str, &[&str])] = &[
    // Transposition typo: the classic case.
    (
        "jooksee",
        &["juoksee", "jaokseen", "jaoksen", "jaokset", "joekseen"],
    ),
    // Doubled-letter typo with an exact-form hit.
    (
        "koiraa",
        &["koiraa", "koiras", "kairaa", "koira", "koiraan"],
    ),
    // Exact hit first, then prefix neighbours (taco/taho/taio/tali).
    ("talo", &["talo", "tali", "taco", "taho", "taio"]),
    // Neighbours found through head and tail rather than prefix.
    ("hemme", &["hemme", "haemme", "hamme", "hehmme", "heimme"]),
    // Trailing-letter deletion where the corrected form also appears.
    (
        "kissaa",
        &["kissaa", "kissa", "kissaan", "kissan", "kissana"],
    ),
    // Already-correct input: the engine must lead with identity.
    (
        "juoksee",
        &["juoksee", "juokse", "juoksen", "juokset", "juoksete"],
    ),
];

fn words(vs: &str, max_n: usize, max_distance: usize) -> Vec<String> {
    suggest(vs, max_n, max_distance)
}

#[test]
fn candidate_words_are_unchanged() {
    for (query, want) in GOLDEN {
        let got = words(query, 5, 2);
        let got: Vec<&str> = got.iter().map(String::as_str).collect();
        assert_eq!(&got, want, "candidate list changed for {query:?}");
    }
}

#[test]
fn detailed_candidates_are_unchanged_too() {
    for (query, want) in GOLDEN {
        let got = suggest_detailed(query, 5, 2);
        let got_words: Vec<&str> = got.iter().map(|s| s.word.as_str()).collect();
        assert_eq!(&got_words, want, "detailed list changed for {query:?}");

        // The ordering contract: Levenshtein ascending, alphabetical
        // tie-break within a distance.
        assert!(
            got.windows(2)
                .all(|w| w[0].edit_distance <= w[1].edit_distance),
            "{query:?}: candidates are not in edit-distance order"
        );
        // And nothing escaped the requested bound, which is what makes
        // `--max-distance` a real filter rather than a hint.
        assert!(
            got.iter().all(|s| s.edit_distance <= 2),
            "{query:?}: a candidate is further than the requested distance"
        );
        // Every candidate carries the deterministic baseline score; if
        // that drifts, ranking explanations become wrong. A distance-1
        // keyboard-adjacent
        // substitution adds the documented 0.05 tie-break bonus
        // (`KEYBOARD_ADJACENT_BONUS`), so the score is either the raw
        // `1/(1+d)` or that plus the bonus.
        for s in &got {
            let base = 1.0 / (1.0 + s.edit_distance as f32);
            let with_bonus = base + 0.05;
            assert!(
                (s.existing_score - base).abs() < 1e-6
                    || (s.existing_score - with_bonus).abs() < 1e-6,
                "{query:?}: existing_score {} for {} edits, expected {base} or {with_bonus}",
                s.existing_score,
                s.edit_distance
            );
        }
    }
}

#[test]
fn candidate_generation_is_deterministic() {
    // Two runs must agree character for character. A hashmap iteration
    // order leaking into the ranking would show up here, and would make
    // every accuracy number in the report non-reproducible.
    for (query, _) in GOLDEN {
        let a = suggest_detailed(query, 5, 2);
        let b = suggest_detailed(query, 5, 2);
        assert_eq!(a.len(), b.len(), "{query:?}: non-deterministic length");
        for (x, y) in a.iter().zip(b.iter()) {
            assert_eq!(x.word, y.word, "{query:?}: non-deterministic word order");
            assert_eq!(
                x.edit_distance, y.edit_distance,
                "{query:?}: distances moved"
            );
            assert_eq!(x.source, y.source, "{query:?}: sources moved");
        }
    }
}

#[test]
fn empty_and_unfindable_inputs_stay_empty() {
    // Truncated or out-of-vocabulary input must not conjure a
    // candidate list where the engine used to produce none.
    assert!(suggest("", 5, 2).is_empty());
    assert!(suggest_detailed("", 5, 2).is_empty());
    assert!(suggest("xyzzy", 5, 0).is_empty());
    assert!(suggest_detailed("xyzzy", 5, 0).is_empty());
}
