"""A hand-coded deterministic ranker for the reranker experiment.

The user's review asked: does the neural reranker learn anything
beyond a carefully-designed deterministic ranker? This module is
that baseline.

Formula:

    score = -edit_distance
          + alpha * log1p(surface_freq[word])
          + beta  * lemma_substring_match
          + gamma * (op_type_prior)

where:

  - edit_distance        : Levenshtein distance (already on candidates).
  - surface_freq[word]   : count of `word` in the Slice-2 train corpus
                            (the same corpus we use to train the NN).
                            log1p dampens the long tail.
  - lemma_substring_match: 1.0 if the candidate's lemma is a contiguous
                            substring of the misspelled word, 0 otherwise.
                            This is the cheap heuristic for "the user
                            probably meant this lemma" -- e.g. for
                            "koirissa" the lemma "koira" is a prefix
                            substring (the i in "koirissa" matches).
  - op_type_prior:        : small bonus/penalty per edit type observed in
                            the candidate's edit_ops:
                              substitution:  0.0  (most plausible)
                              deletion:      0.0
                              insertion:    -0.1  (more disruptive)
                              transposition: 0.1  (Finnish typos often
                                                 swap adjacent keys)

The weights `alpha, beta, gamma` are tuned on the dev split to give
the deterministic baseline a fair shot.
"""

from __future__ import annotations

import json
import math
from collections import Counter
from pathlib import Path


# ---------------------------------------------------------------------------
#   Frequency source.
# ---------------------------------------------------------------------------


_FREQ_PATH = Path(__file__).parent.parent.parent / "data" / "train" / "train.jsonl"
_FREQ_CACHE: dict[str, int] | None = None


def _build_surface_freq() -> Counter:
    """Count surface-form occurrences in the Slice-2 train corpus.

    The corpus is generated by applying corruption strategies to the
    Kotus databases, so its frequency distribution is biased toward
    the same lemmas the reranker will see at test time. Good enough
    for a deterministic baseline; production would re-train the
    counter on a real Finnish corpus.
    """
    counter: Counter = Counter()
    with _FREQ_PATH.open() as fh:
        for line in fh:
            line = line.strip()
            if not line:
                continue
            try:
                row = json.loads(line)
            except json.JSONDecodeError:
                continue
            sf = row.get("surface_form")
            if sf:
                counter[sf] += 1
    return counter


def surface_freq(word: str) -> int:
    global _FREQ_CACHE
    if _FREQ_CACHE is None:
        _FREQ_CACHE = _build_surface_freq()
    return _FREQ_CACHE.get(word, 0)


# ---------------------------------------------------------------------------
#   Edit-op pattern prior.
# ---------------------------------------------------------------------------

OP_PRIOR = {
    "sub": 0.0,
    "del": 0.0,
    "ins": -0.1,
    "trans": 0.1,
}


def edit_pattern_prior(ops: list[dict]) -> float:
    return sum(OP_PRIOR.get(op.get("op", ""), 0.0) for op in ops)


# ---------------------------------------------------------------------------
#   Lemma substring heuristic.
# ---------------------------------------------------------------------------


def lemma_substring_score(misspelled: str, lemma: str) -> float:
    """Return 1.0 if `lemma` is a contiguous substring of `misspelled`,
    else 0.0. This is a very cheap heuristic for "the user probably
    had this lemma in mind" -- it favours candidates whose lemma is
    visible in the misspelling even after corruption.
    """
    if not lemma or not misspelled:
        return 0.0
    return 1.0 if lemma in misspelled else 0.0


# ---------------------------------------------------------------------------
#   The ranker.
# ---------------------------------------------------------------------------


def deterministic_score(
    misspelled: str,
    candidate: dict,
    *,
    alpha: float = 0.05,
    beta: float = 0.5,
    gamma: float = 1.0,
) -> float:
    """Compute the deterministic ranker's score for one candidate.

    Lower (more negative) edit_distance dominates; the bonuses are
    small by design so the ranker stays close to the engine's edit-
    distance ordering except where a feature clearly helps.
    """
    ed = float(candidate.get("edit_distance", 0))
    word = candidate.get("word", "")
    lemma = candidate.get("lemma", "")
    ops = candidate.get("edit_ops", [])
    score = -ed
    score += beta * lemma_substring_score(misspelled, lemma)
    score += alpha * math.log1p(surface_freq(word))
    score += gamma * edit_pattern_prior(ops)
    return score


def deterministic_rank(
    misspelled: str,
    candidates: list[dict],
    **kwargs,
) -> list[float]:
    """Score every candidate in the list, returning scores in input
    order. The caller does the argmax."""
    return [deterministic_score(misspelled, c, **kwargs) for c in candidates]


if __name__ == "__main__":
    # Smoke test: print the frequencies of a few common words and
    # the deterministic score for an obvious near-miss.
    print("surface_freq:")
    for w in ["talo", "kissa", "koira", "kori", "korissa", "koirissa", "juoksee"]:
        print(f"  {w:<10}  count={surface_freq(w):>6}")
    print()
    print("deterministic_score:")
    cases = [
        ("koirissa", {"word": "koirissa", "lemma": "koira",
                       "edit_distance": 0, "edit_ops": []}),
        ("koirissa", {"word": "koiraissa", "lemma": "koiras",
                       "edit_distance": 1, "edit_ops": []}),
        ("koirissa", {"word": "koirassa", "lemma": "koira",
                       "edit_distance": 1, "edit_ops": []}),
        ("koirissa", {"word": "koirista", "lemma": "koira",
                       "edit_distance": 1, "edit_ops": []}),
    ]
    for ms, c in cases:
        s = deterministic_score(ms, c)
        print(f"  {ms:<12} -> {c['word']:<12}  ed={c['edit_distance']}  "
              f"score={s:+.3f}")