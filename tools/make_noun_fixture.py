"""Generate the noun-class lemma fixture used by the two-trees equivalence test.

`src/expand/nominals/` and `src/expand/nominals-refactored/` are the same
grammar in two states: one is the tree in use, the other is the tree being
refactored onto the verb side's shape. The refactor is only safe if the two
agree form for form, so the agreement is a test rather than a script somebody
has to remember to run -- and a test needs its inputs in the repository, not
in the uncommitted `data/`.

The input the test wants is *every* dispatch key with a couple of real words
behind it, because the claim is "the two trees agree", and a claim about the
trees is only as good as its coverage of the dispatch table. Each key gets up
to six words, chosen so harmony varies: `Builder::new` decides front or back
from the word, so a class tested only on back words would not notice a
harmony that stopped being consulted.

Selection is deterministic -- first by sort order, then by first front-harmony
word, then first back-harmony word -- so regenerating the fixture on a
different machine produces the same file and a spurious diff means something
actually moved.

Usage:
    python3 tools/make_noun_fixture.py > tests/fixtures/noun_classes.txt
"""

import re
import sqlite3
import sys

DB = "file:data/kotus_nomines.sqlite?mode=ro"
DISPATCH = "src/expand/nominals/mod.rs"
OUT = "tests/fixtures/noun_classes.txt"

# Words to take per class, in order of preference. The first two are plain
# sort order so the fixture is not all harmony corner-cases; the front and back
# words come next so a class is tested on both halves of the alternation; the
# last two top up short classes.
PER_CLASS = ("first", "first", "front", "back", "first", "first")

# Words that have to be in the fixture whatever the sort order says, because
# selection by shape cannot reach them: a lemma whose citation form is not the
# stem its class builds from. Sort order takes the first words of the class and
# these are never among them, and a class that only ever gets its ordinary
# words is tested only on ordinary words.
#
# The one group so far is class 10's `-n` numerals, where the lemma carries the
# genitive ending and the stem is the lemma without it (`kahdeksan` is
# `kahdeksa` + `n`), which is the branch added in FIX_ME item 17. Both halves
# matter here: one without the other would let the two trees diverge on exactly
# the shape that differs from every other lemma in the class.
PINNED = {"10": ("kahdeksan", "seitsemän", "yhdeksän")}


def front(lemma):
    """`nominals::utility::front`: the last non-neutral vowel decides.

    `e` and `i` are neutral and skipped; no harmonic vowel at all is front.
    A wrong verdict here would only narrow the sample, never fail the test,
    so this is allowed to drift from the Rust without breaking anything.
    """
    for c in reversed(lemma):
        if c in "äöyÄÖY":
            return True
        if c in "aouôAOU":
            return False
    return True


def dispatch_keys():
    """The class cells `nominals::dispatch` routes on."""
    src = open(DISPATCH, encoding="utf-8").read()
    return sorted(set(re.findall(r'^\s+"([^"]*)" =>', src, re.M)))


def pick_for(pool, fronts, backs):
    """Up to six words for one class: two in sort order, then one of each
    harmony, then two more in sort order."""
    used, rows = set(), []
    for want in PER_CLASS:
        src = pool if want == "first" else fronts if want == "front" else backs
        pick = next((w for w in src if w not in used), None)
        if pick is not None:
            used.add(pick)
            rows.append(pick)
    return rows


def main():
    db = sqlite3.connect(DB, uri=True)
    words = {}
    for lemma, cell in db.execute("SELECT lemma,class FROM base"):
        words.setdefault(cell, set()).add(lemma)

    keys = dispatch_keys()
    thin = []
    rows = []
    for key in keys:
        pool = sorted(words.get(key, ()))
        if not pool:
            thin.append(key)
            continue
        fronts = [w for w in pool if front(w)]
        backs = [w for w in pool if not front(w)]
        picked = pick_for(pool, fronts, backs)
        # Pinned words are appended after the sample for their class, and only if
        # the sample did not reach them on its own, so a regeneration keeps the
        # six words it has always chosen and adds to them rather than swapping.
        picked += [
            w for w in PINNED.get(key, ()) if w in words.get(key, ()) and w not in picked
        ]
        rows.extend((key, lemma) for lemma in picked)

    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("# class\tlemma -- generated by tools/make_noun_fixture.py\n")
        for key, lemma in rows:
            fh.write(f"{key}\t{lemma}\n")

    print(f"{len(keys)} dispatch keys, {len(rows)} (class, lemma) pairs -> {OUT}",
          file=sys.stderr)
    if thin:
        print(f"{len(thin)} keys have no lemma in the lexicon: {thin}",
              file=sys.stderr)
    # Every key must appear, or the test is quietly covering less than it says.
    covered = {k for k, _ in rows}
    missing = [k for k in keys if k not in covered]
    assert not missing, f"uncovered dispatch keys: {missing}"
    return 0


if __name__ == "__main__":
    sys.exit(main())