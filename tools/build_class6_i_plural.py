"""Generate the class-6 per-lemma `-iden`/`-itten`/`-ita` mask.

Class 6 normally confirms all three `-i`-plural alternants (`aateli`:
`aatelien`, `aateleiden`, `aateleitten`, `aateleita`), but many class-6
loanwords confirm only some of them, or none. The inflector needs a per-lemma
answer, not a class-wide default.

The mask has bit 1 for `-iden`, bit 2 for `-itten`, bit 4 for `-ita`; a lemma
with none is omitted and falls back to `IPlural::NONE`. The source is the
materialised nominal oracle, the same source the class reports use.

Usage:

    python3 tools/build_class6_i_plural.py
"""

from __future__ import annotations

import os
import sqlite3

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DB = os.path.join(REPO, "data", "kotus_nomines.sqlite")
OUT = os.path.join(REPO, "src", "expand", "nominals", "class_6_i_plural.rs")


def rust_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def masks() -> dict[str, int]:
    db = sqlite3.connect(f"file:{DB}?mode=ro", uri=True)
    rows = db.execute(
        "SELECT b.lemma, f.form, f.\"case\", f.number"
        " FROM base b JOIN forms f USING (lemma, homonym)"
        " WHERE b.class='6' AND f.ok='both'"
    )
    out: dict[str, int] = {}
    for lemma, form, case, number in rows:
        mask = 0
        if case == "genitive" and number == "plural":
            if form.endswith("iden"):
                mask |= 1
            if form.endswith("itten"):
                mask |= 2
        elif case == "partitive" and number == "plural" and (
            form.endswith("ita") or form.endswith("itä")
        ):
            mask |= 4
        if mask:
            out[lemma] = out.get(lemma, 0) | mask
    db.close()
    return out


def main() -> int:
    data = masks()
    lines = [
        "// SPDX-License-Identifier: MIT OR Apache-2.0",
        "// Class-6 `-iden`/`-itten`/`-ita` confirmation, generated by",
        "// `tools/build_class6_i_plural.py` from the nominal oracle.",
        "//",
        "// Bit 1 = `-iden`, bit 2 = `-itten`, bit 4 = `-ita`. A lemma with",
        "// none is absent and falls back to `IPlural::NONE`. Do not edit.",
        "",
        "/// Sorted by lemma; use `binary_search_by_key`.",
        "pub const I_PLURAL: &[(&str, u8)] = &[",
    ]
    for lemma in sorted(data):
        lines.append(f"    ({rust_str(lemma)}, {data[lemma]}),")
    lines.append("];")
    lines.append("")
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print(f"{OUT}: {len(data)} lemmas")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
