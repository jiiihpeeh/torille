//! Front-coded set and map emitters.
//!
//! Split out of `build.rs`; `main` calls the three public entry points.
//! `write_varint` and `human_bytes` stay in the crate root because the
//! Huffman writer shares them.

use std::collections::BTreeMap;
use std::fs;
use std::path::Path;

use crate::map_builders::huffman::emit_huffman_set;
use crate::{human_bytes, write_varint};

/// Emit the compile-time form subset as a front-coded set blob.
///
/// The filter keeps only the cases users type most often -- the bare lemma
/// (nominative singular, no possessive) and the genitive singular (no
/// possessive). The heuristic picks coverage of the words the typing path
/// actually sees; missing forms fall through to the slow check. We don't
/// have corpus frequency, so this is a "common spelling" proxy, not a
/// true top-N.
///
/// The keys are sorted and front-coded exactly like the stem maps (see
/// `src/expand/static_table.rs`), so the compiler only sees `include_bytes!`
/// and the strings are not duplicated in a `phf` table.
///
/// **Reuse path**: if `blob_path` already exists and the CSV is *missing*,
/// skip the read-and-emit entirely -- a fresh build on a clone without the
/// CSV reuses the committed precomputed blob.
/// Emit an empty `SST2` set (zero keys).
///
/// The bootstrap case for a fresh clone: `data/all_forms.csv` is generated by
/// `gen_all_forms` and is not tracked, so if neither the CSV nor a committed
/// set is available the crate must still compile far enough to build that
/// tool. An empty set makes the fast form probe miss everything; the slow
/// check still works.
pub(crate) fn emit_empty_set(blob_path: &Path) {
    let mut blob = Vec::with_capacity(40);
    blob.extend_from_slice(b"SST2");
    for value in [
        0u32, // key_count
        0,    // restart_count
        40,   // restarts_off
        40,   // keys_off
        40,   // ids_off
        40,   // overflow_off
        40,   // string_offsets_off
        0,    // string_count
        40,   // strings_off
    ] {
        blob.extend_from_slice(&value.to_le_bytes());
    }
    fs::write(blob_path, &blob).unwrap_or_else(|e| panic!("{}: {e}", blob_path.display()));
}

pub(crate) fn emit_front_coded_set(csv_path: &Path, blob_path: &Path) {
    if !csv_path.exists() && blob_path.exists() {
        eprintln!(
            "build.rs: {} missing but {} present -- reusing",
            csv_path.display(),
            blob_path.display(),
        );
        return;
    }
    use std::collections::BTreeSet;
    let csv = match fs::read_to_string(csv_path) {
        Ok(s) => s,
        Err(e) => panic!(
            "build.rs: could not read {}: {e}; \
             run `cargo run --release -p torille-tools --bin gen_all_forms` first",
            csv_path.display(),
        ),
    };
    let mut seen: BTreeSet<String> = BTreeSet::new();
    for line in csv.lines() {
        if line.is_empty() {
            continue;
        }
        // CSV columns: form \t lemma \t case \t number \t possessive
        let mut cols = line.split('\t');
        let form = cols.next().unwrap_or(""); // 1: form
        let lemma = cols.next().unwrap_or(""); // 2: lemma
        if crate::rejected::contains(lemma) {
            continue;
        }
        let case = cols.next().unwrap_or(""); // 3: case
        let number = cols.next().unwrap_or(""); // 4: number
        let possessive = cols.next().unwrap_or(""); // 5: possessive
        if form.is_empty() || form.contains('\0') {
            continue;
        }
        // The oracle's class-1 plural-only lemmas (`housut`, `aivot`) carry
        // a bogus genitive singular `housutn`/`aivotn` beside the real
        // `housuja`/`aivoja`. The engine now declines these from the dropped
        // stem; keep the bad oracle row out of the fast form set too.
        if case == "genitive"
            && number == "singular"
            && lemma.ends_with('t')
            && form == format!("{lemma}n")
        {
            continue;
        }
        // Lemmas (nominative singular, no possessive) and
        // genitive singular forms (no possessive). The "no
        // possessive" filter trims 2.86 M possessive variants
        // that the typing path rarely sees.
        if !possessive.is_empty() {
            continue;
        }
        // A plural-only lemma (`atulat`, `kihlat`) has its citation in the
        // nominative plural, not the singular; the engine tags it that way,
        // so keep the form when it is the lemma itself.
        let citation_plural = case == "nominative" && number == "plural" && form == lemma;
        let include = (case == "nominative" && number == "singular")
            || (case == "genitive" && number == "singular")
            || citation_plural;
        if !include {
            continue;
        }
        seen.insert(form.to_string());
    }
    let keys: Vec<String> = seen.into_iter().collect();
    eprintln!(
        "build.rs: {}: {} lemma + genitive-singular forms",
        csv_path.display(),
        keys.len(),
    );
    emit_front_coded_keys(blob_path, &keys);
}

/// Emit `data/proper_name_forms.csv` (`form<TAB>name<TAB>case`) as a Huffman-coded
/// set of forms.
///
/// Wikidata supplies the names, Omorfi the singular cases; the typing path
/// only needs to know that a surface form is a name, so a set (no values) is
/// enough. Keys are lowercased because the fast path lowercases before
/// probing. The set is front-coded and entropy-coded (`HST1`); see
/// [`emit_huffman_set`].
pub(crate) fn emit_proper_names(csv_path: &Path, blob_path: &Path) {
    if !csv_path.exists() && blob_path.exists() {
        eprintln!(
            "build.rs: {} missing but {} present -- reusing",
            csv_path.display(),
            blob_path.display(),
        );
        return;
    }
    use std::collections::BTreeSet;
    let csv = fs::read_to_string(csv_path).unwrap_or_else(|e| {
        panic!(
            "build.rs: could not read {}: {e}; \
             run `python3 tools/oracle/build_proper_name_forms.py` first",
            csv_path.display(),
        )
    });
    let mut seen: BTreeSet<String> = BTreeSet::new();
    for line in csv.lines() {
        let Some((form, _name)) = line.split_once('\t') else {
            continue;
        };
        let form = form.trim();
        if form.is_empty() || form.contains('\0') {
            continue;
        }
        seen.insert(form.to_lowercase());
    }
    let keys: Vec<String> = seen.into_iter().collect();
    eprintln!(
        "build.rs: {}: {} proper-name forms",
        csv_path.display(),
        keys.len(),
    );
    emit_huffman_set(blob_path, &keys);
}

/// Emit `data/proper_name_forms.csv` (`form<TAB>name<TAB>case`) as a front-coded
/// `form -> name` map.
///
/// [`emit_proper_names`] keeps only the surface set because the typing path
/// only needs "is this a name?". A caller that wants the lemma behind the
/// surface (`Mainen` -> `Maine`, `Helsingin` -> `Helsinki`) needs the value,
/// so this companion blob keeps it. Keys are lowercased like the set; the
/// values keep the source's capitalisation.
pub(crate) fn emit_proper_name_lemmas(csv_path: &Path, extra_path: &Path, blob_path: &Path) {
    if !csv_path.exists() && blob_path.exists() {
        eprintln!(
            "build.rs: {} missing but {} present -- reusing",
            csv_path.display(),
            blob_path.display(),
        );
        return;
    }
    let csv = fs::read_to_string(csv_path).unwrap_or_else(|e| {
        panic!(
            "build.rs: could not read {}: {e}; \
             run `python3 tools/oracle/build_proper_name_forms.py` first",
            csv_path.display(),
        )
    });
    let mut entries: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for line in csv.lines() {
        let Some((form, name, _case)) = split_name_row(line) else {
            continue;
        };
        let values = entries.entry(form.to_lowercase()).or_default();
        if !values.iter().any(|seen| seen == &name) {
            values.push(name);
        }
    }
    if extra_path.exists() {
        let extra = fs::read_to_string(extra_path).unwrap_or_default();
        for line in extra.lines() {
            let Some((form, name, _case)) = split_name_row(line) else {
                continue;
            };
            let values = entries.entry(form.to_lowercase()).or_default();
            if !values.iter().any(|seen| seen == &name) {
                values.push(name);
            }
        }
    }
    for values in entries.values_mut() {
        values.sort_unstable();
    }
    let entries: Vec<(String, Vec<String>)> = entries.into_iter().collect();
    eprintln!(
        "build.rs: {}: {} proper-name form -> lemma entries",
        csv_path.display(),
        entries.len(),
    );
    write_front_coded_map(blob_path, &entries);
}

/// Emit the `form -> case` map from the third column of
/// `data/proper_name_forms.csv`.
///
/// The syntax layer needs the case a name surface is in (`Helsingissä` is
/// inessive, `Liisalle` allative). Omorfi already generated the form for a
/// named cell, so the generator writes the cell's case beside it. The case is
/// stored as torille's case name, not Omorfi's code.
pub(crate) fn emit_proper_name_cases(csv_path: &Path, extra_path: &Path, blob_path: &Path) {
    if !csv_path.exists() && blob_path.exists() {
        eprintln!(
            "build.rs: {} missing but {} present -- reusing",
            csv_path.display(),
            blob_path.display(),
        );
        return;
    }
    let csv = fs::read_to_string(csv_path).unwrap_or_else(|e| {
        panic!(
            "build.rs: could not read {}: {e}; \
             run `python3 tools/oracle/build_proper_name_forms.py` first",
            csv_path.display(),
        )
    });
    let mut entries: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for line in csv.lines() {
        let Some((form, _name, case)) = split_name_row(line) else {
            continue;
        };
        let Some(case) = case_name(&case) else {
            continue;
        };
        let values = entries.entry(form.to_lowercase()).or_default();
        if !values.iter().any(|seen| seen == case) {
            values.push(case.to_string());
        }
    }
    if extra_path.exists() {
        let extra = fs::read_to_string(extra_path).unwrap_or_default();
        for line in extra.lines() {
            let Some((form, _name, case)) = split_name_row(line) else {
                continue;
            };
            let Some(case) = case_name(&case) else {
                continue;
            };
            let values = entries.entry(form.to_lowercase()).or_default();
            if !values.iter().any(|seen| seen == case) {
                values.push(case.to_string());
            }
        }
    }
    eprintln!(
        "build.rs: {}: {} proper-name form -> case entries",
        csv_path.display(),
        entries.len(),
    );
    let entries: Vec<(String, Vec<String>)> = entries.into_iter().collect();
    write_front_coded_map(blob_path, &entries);
}

/// Split a name row into `(form, name, case)`. The curated extras are the one
/// place a row may have only two columns; its case is then empty.
fn split_name_row(line: &str) -> Option<(String, String, String)> {
    let mut fields = line.split('\t');
    let form = fields.next()?.trim();
    let name = fields.next()?.trim();
    let case = fields.next().unwrap_or("").trim();
    if form.is_empty() || name.is_empty() || form.contains('\0') || name.contains('\0') {
        return None;
    }
    Some((form.to_string(), name.to_string(), case.to_string()))
}

/// Omorfi's case code to torille's case name. Unknown codes are dropped
/// rather than guessed.
fn case_name(code: &str) -> Option<&'static str> {
    Some(match code {
        "NOM" => "nominative",
        "GEN" => "genitive",
        "PAR" => "partitive",
        "ILL" => "illative",
        "INE" => "inessive",
        "ELA" => "elative",
        "ADE" => "adessive",
        "ABL" => "ablative",
        "ALL" => "allative",
        "ESS" => "essive",
        "TRA" => "translative",
        "ABE" => "abessive",
        "ACC" => "accusative",
        "INS" => "instructive",
        "COM" => "comitative",
        "PRO" => "prolative",
        _ => return None,
    })
}

/// Emit `lemma -> cases` from `data/verb_rection.csv`.
///
/// One row is one valency frame: `lemma,case,frame,priority,note`. The CSV is
/// curated and comma-free in its note column; a note with a comma needs a
/// quoted CSV reader, which this small table does not justify.
pub(crate) fn emit_verb_rection(csv_path: &Path, blob_path: &Path) {
    if !csv_path.exists() && blob_path.exists() {
        eprintln!(
            "build.rs: {} missing but {} present -- reusing",
            csv_path.display(),
            blob_path.display(),
        );
        return;
    }
    let csv = fs::read_to_string(csv_path).unwrap_or_else(|e| {
        panic!(
            "build.rs: could not read {}: {e}",
            csv_path.display(),
        )
    });
    let mut entries: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for line in csv.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with("lemma,") {
            continue;
        }
        let mut fields = line.splitn(5, ',');
        let Some(lemma) = fields.next().map(str::trim).filter(|s| !s.is_empty()) else {
            continue;
        };
        let Some(case) = fields.next().map(str::trim).filter(|s| !s.is_empty()) else {
            continue;
        };
        let values = entries.entry(lemma.to_string()).or_default();
        if !values.iter().any(|seen| seen == case) {
            values.push(case.to_string());
        }
    }
    eprintln!(
        "build.rs: {}: {} verb-rection lemmas",
        csv_path.display(),
        entries.len(),
    );
    let entries: Vec<(String, Vec<String>)> = entries.into_iter().collect();
    write_front_coded_map(blob_path, &entries);
}

/// Emit `lemma -> argument frames` from `data/verb_arguments.csv`.
///
/// One row is `lemma,slot,case,requirement,note`; the value is encoded as
/// `slot:case:requirement` so the shared front-coded map reader can carry it.
/// The table is tiny and curated, and its notes are comma-free for the same
/// reason as `verb_rection.csv`.
